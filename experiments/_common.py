def load_config(name: str) -> dict:
    with (CONFIGS / f"{name}.yaml").open() as fh:
        return yaml.safe_load(fh)


def figure(width: float = COLUMN_WIDTH, height: float = 2.0, **kwargs):
    plt.rcParams.update(STYLE)
    return plt.subplots(figsize=(width, height), **kwargs)


def save_figure(fig, name: str) -> Path:
    FIGS.mkdir(parents=True, exist_ok=True)
    path = FIGS / f"{name}.pdf"
    fig.savefig(path, metadata={"CreationDate": None, "ModDate": None})
    plt.close(fig)
    return path


def _macro_name(prefix: str, key: str) -> str:
    words = re.split(r"[_\-\s]+", f"{prefix} {key}")
    name = "".join(w[:1].upper() + w[1:] for w in words if w)
    if not name.isalpha():
        raise ValueError(f"macro name must be letters only: {name}")
    return name


def write_numbers(experiment: str, numbers: dict[str, str]) -> Path:
    """Write paper/generated/<experiment>.tex with one \\newcommand per number.

    Keys are words of letters separated by '_', '-' or spaces (LaTeX macro
    names cannot hold digits); values are preformatted strings so rounding is
    decided by the experiment.
    """
    GENERATED.mkdir(parents=True, exist_ok=True)
    lines = [f"% Generated by experiments/{experiment}.py -- do not edit.\n"]
    for key, value in numbers.items():
        lines.append(f"\\newcommand{{\\{_macro_name(experiment, key)}}}{{{value}}}\n")
    path = GENERATED / f"{experiment}.tex"
    path.write_text("".join(lines))
    return path


def write_results(experiment: str, payload: dict) -> Path:
    RESULTS.mkdir(parents=True, exist_ok=True)
    path = RESULTS / f"{experiment}.json"
    path.write_text(json.dumps(payload, indent=2, default=float))
    return path


def fmt_int(x: float) -> str:
    """Thousands with a thin space, as in the IEEE style: 12\\,345."""
    s = f"{abs(round(x)):,}".replace(",", "\\,")
    return ("$-$" if round(x) < 0 else "") + s


def fmt_float(x: float, digits: int = 1) -> str:
    if x != x:  # NaN: the quantity is undefined, e.g. the rank correlation of a constant score
        return "--"
    s = f"{x:.{digits}f}"
    return s.replace("-", "$-$") if float(s) != 0 else s.lstrip("-")
